/**
 * Regenerates the checked-in, offline trajectory pack. Run manually; the web
 * application never calls Horizons. Node 20+ supplies fetch and Web Crypto.
 */
import { createHash } from 'node:crypto'
import { mkdir, writeFile } from 'node:fs/promises'

const API = 'https://ssd.jpl.nasa.gov/api/horizons.api'
const OUTPUT = new URL('../src/data/horizonsTrajectories.ts', import.meta.url)
const MANIFEST = new URL('../src/data/horizons-provenance.json', import.meta.url)
const requests = [
  { id: 'voyager2', command: '-32', start: '1977-08-21', stop: '2031-01-01' },
  { id: 'newhorizons', command: '-98', start: '2006-01-20', stop: '2031-01-01' },
]

function queryFor({ command, start, stop }) {
  return new URLSearchParams({
    format: 'text', COMMAND: `'${command}'`, MAKE_EPHEM: 'YES', EPHEM_TYPE: 'VECTORS',
    CENTER: '500@10', REF_PLANE: 'FRAME', REF_SYSTEM: 'ICRF', VEC_CORR: 'NONE',
    OUT_UNITS: 'AU-D', TIME_TYPE: 'TDB', START_TIME: `'${start}'`, STOP_TIME: `'${stop}'`,
    STEP_SIZE: "'30 d'", VEC_TABLE: '3', OBJ_DATA: 'NO',
  }).toString()
}

function parseVectors(text) {
  const body = text.match(/\$\$SOE([\s\S]*?)\$\$EOE/)?.[1]
  if (!body) throw new Error(`Horizons response did not contain a vector table:\n${text.slice(0, 1000)}`)
  const records = []
  const rows = body.trim().split(/\r?\n/)
  for (let index = 0; index < rows.length; index += 4) {
    const epoch = rows[index]?.match(/^\s*([0-9.]+)/)?.[1]
    const position = rows[index + 1]?.match(/X\s*=\s*([-+.0-9E]+)\s+Y\s*=\s*([-+.0-9E]+)\s+Z\s*=\s*([-+.0-9E]+)/)
    const velocity = rows[index + 2]?.match(/VX\s*=\s*([-+.0-9E]+)\s+VY\s*=\s*([-+.0-9E]+)\s+VZ\s*=\s*([-+.0-9E]+)/)
    if (!epoch || !position || !velocity) throw new Error(`Could not parse Horizons vector near row ${index + 1}`)
    records.push([Number(epoch), ...position.slice(1).map(Number), ...velocity.slice(1).map(Number)])
  }
  return records
}

const results = []
for (const request of requests) {
  const query = queryFor(request)
  const response = await fetch(`${API}?${query}`)
  const raw = await response.text()
  if (!response.ok) throw new Error(`Horizons ${request.id}: ${response.status}\n${raw}`)
  const samples = parseVectors(raw)
  results.push({
    ...request, query, rawSha256: createHash('sha256').update(raw).digest('hex'),
    samples,
  })
}

await mkdir(new URL('../src/data/', import.meta.url), { recursive: true })
const pack = `/** Generated by scripts/fetch-horizons-trajectories.mjs. Do not hand edit. */
export type HorizonsVectorSample = readonly [jdTdb: number, xAu: number, yAu: number, zAu: number, vxAuPerDay: number, vyAuPerDay: number, vzAuPerDay: number]
export const HORIZONS_TRAJECTORIES: Record<'voyager2' | 'newhorizons', readonly HorizonsVectorSample[]> = ${JSON.stringify(Object.fromEntries(results.map(({ id, samples }) => [id, samples])))}
`
await writeFile(OUTPUT, pack)
await writeFile(MANIFEST, `${JSON.stringify({
  generatedAt: new Date().toISOString(), endpoint: API,
  frame: 'Sun-centered (500@10), geometric (VEC_CORR=NONE), ICRF reference plane/system, TDB, AU and AU/day',
  sampling: '30 days; first and last samples follow Horizons START_TIME and STOP_TIME inclusion',
  trajectories: results.map(({ id, command, start, stop, query, rawSha256, samples }) => ({ id, command, start, stop, query, rawSha256, sampleCount: samples.length, firstJdTdb: samples[0][0], lastJdTdb: samples.at(-1)[0] })),
}, null, 2)}\n`)
console.log(`Wrote ${results.map(({ id, samples }) => `${id}: ${samples.length}`).join(', ')}`)
